//
//  Pure model for the clipboard history: entries, dedupe, limits, search.
//

import Foundation

struct ClipboardEntry: Codable, Identifiable, Equatable {
    enum Kind: String, Codable {
        case text, link, image, files
    }

    var id = UUID()
    var kind: Kind
    /// Plain text, URL string, or newline-separated file paths.
    var text: String
    /// File name of the stored PNG for image entries.
    var imageFile: String?
    /// Text recognized in an image entry.
    var ocrText: String?
    var sourceApp: String?
    var date = Date()
    var pinned = false

    /// Identity used for dedupe. Images are keyed by a content hash stored in `text`.
    var dedupeKey: String { "\(kind.rawValue):\(text)" }

    var searchableText: String { [text, ocrText ?? ""].joined(separator: "\n") }
}

struct ClipboardHistory: Codable, Equatable {
    private(set) var entries: [ClipboardEntry] = []

    /// Inserts `entry` at the top. A duplicate is moved to the top (keeping its
    /// pin and OCR text) instead of added twice. Returns entries evicted by the
    /// limit; pinned entries are never evicted.
    @discardableResult
    mutating func insert(_ entry: ClipboardEntry, limit: Int) -> [ClipboardEntry] {
        var entry = entry
        if let index = entries.firstIndex(where: { $0.dedupeKey == entry.dedupeKey }) {
            let old = entries.remove(at: index)
            entry.id = old.id
            entry.pinned = old.pinned
            entry.ocrText = entry.ocrText ?? old.ocrText
            entry.imageFile = old.imageFile ?? entry.imageFile
        }
        entries.insert(entry, at: 0)
        return trim(limit: limit)
    }

    mutating func trim(limit: Int) -> [ClipboardEntry] {
        var evicted: [ClipboardEntry] = []
        var unpinnedSeen = 0
        entries.removeAll { entry in
            guard !entry.pinned else { return false }
            unpinnedSeen += 1
            if unpinnedSeen > max(limit, 0) {
                evicted.append(entry)
                return true
            }
            return false
        }
        return evicted
    }

    mutating func update(_ id: UUID, _ change: (inout ClipboardEntry) -> Void) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        change(&entries[index])
    }

    @discardableResult
    mutating func remove(_ id: UUID) -> ClipboardEntry? {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return nil }
        return entries.remove(at: index)
    }

    /// Removes all unpinned entries and returns them.
    mutating func clearUnpinned() -> [ClipboardEntry] {
        let removed = entries.filter { !$0.pinned }
        entries.removeAll { !$0.pinned }
        return removed
    }

    /// Pinned first, then most recent; filtered by every whitespace-separated term.
    func filtered(by query: String) -> [ClipboardEntry] {
        let terms = query.lowercased().split(whereSeparator: \.isWhitespace)
        let matching = terms.isEmpty ? entries : entries.filter { entry in
            let haystack = entry.searchableText.lowercased()
            return terms.allSatisfy { haystack.contains($0) }
        }
        return matching.filter(\.pinned) + matching.filter { !$0.pinned }
    }

    /// Pasteboard types set by password managers and other apps that ask
    /// clipboard tools not to record them (nspasteboard.org conventions).
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    static func shouldIgnore(types: [String]) -> Bool {
        types.contains(where: ignoredTypes.contains)
    }
}
